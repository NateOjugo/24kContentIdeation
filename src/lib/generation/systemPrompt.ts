export type VoiceCorrection = { rule: string; reinforced_count: number };

/** Voice Correction Log lives in Tier 1 but is capped at ~30 entries. */
export function voiceCorrectionsBlock(corrections: VoiceCorrection[]): string {
  if (corrections.length === 0) return "";
  const rules = corrections
    .map((c) => `- ${c.rule}${c.reinforced_count > 1 ? ` (reinforced x${c.reinforced_count})` : ""}`)
    .join("\n");
  return `\n\n## VOICE CORRECTION LOG — learned from Nate's actual edits, apply on top of Voice DNA\n${rules}`;
}
